// ---------------------------------------------------------------- zod procedure inputs
// The runtime validators are the OpenAPI request schemas above, emitted as zod source (AD-16,
// AD-SYS-8 rules 1–2): every object is strict, so a role-like or omitted key is refused.
{
  const q = (s) => `'${String(s).replace(/[\\']/g, '\\$&')}'`;
  const used = [];
  const state = new Map(); // component -> 'visiting' | 'done'
  const visit = (name) => {
    if (state.get(name) === 'done') return;
    if (state.get(name) === 'visiting') throw new Error(`zod inputs: ${name} is recursive`);
    if (['z', 'INPUTS'].includes(name)) throw new Error(`zod inputs: component name ${name} is reserved`);
    state.set(name, 'visiting');
    const src = zodOf(components.get(name));
    state.set(name, 'done');
    used.push(`const ${name} = ${src};`);
  };
  const bounded = (src, s, lo, hi) => `${src}${lo in s ? `.min(${s[lo]})` : ''}${hi in s ? `.max(${s[hi]})` : ''}`;
  // A keyword outside this set would be silently dropped from the wire check, so it fails the build.
  const HANDLED = new Set(['$ref', 'anyOf', 'enum', 'const', 'not', 'type', 'format', 'minLength', 'maxLength', 'pattern', 'minimum', 'maximum', 'items', 'minItems', 'maxItems', 'properties', 'required', 'additionalProperties', 'description', 'title', 'examples']);
  function zodOf(s) {
    const unhandled = Object.keys(s).filter((k) => !HANDLED.has(k) && !k.startsWith('x-'));
    if (unhandled.length) throw new Error(`zod inputs: unsupported keyword(s) ${unhandled.join(', ')} in ${JSON.stringify(s)}`);
    if (s.$ref) { const name = s.$ref.split('/').pop(); visit(name); return name; }
    if (s.anyOf) {
      const rest = s.anyOf.filter((b) => b.type !== 'null');
      const nullable = rest.length < s.anyOf.length ? '.nullable()' : '';
      return `${rest.length === 1 ? zodOf(rest[0]) : `z.union([${rest.map(zodOf).join(', ')}])`}${nullable}`;
    }
    if (s.enum) {
      const values = s.enum.filter((v) => v !== null);
      if (values.some((v) => typeof v !== 'string')) throw new Error(`zod inputs: z.enum takes strings only, got ${JSON.stringify(s.enum)}`);
      return `z.enum([${values.map(q).join(', ')}])${values.length < s.enum.length ? '.nullable()' : ''}`;
    }
    if ('const' in s) return `z.literal(${typeof s.const === 'string' ? q(s.const) : JSON.stringify(s.const)})`;
    if (s.not && !Object.keys(s.not).length) return 'z.never()';
    switch (s.type) {
      case 'string':
        if (s.format === 'date-time') return 'z.iso.datetime()';
        if (s.format === 'date') return 'z.iso.date()';
        if (s.format) throw new Error(`zod inputs: unsupported string format ${s.format}`);
        return `${bounded('z.string()', s, 'minLength', 'maxLength')}${s.pattern ? `.regex(new RegExp(${JSON.stringify(s.pattern)}))` : ''}`;
      case 'integer': return bounded('z.number().int()', s, 'minimum', 'maximum');
      case 'number': return bounded('z.number()', s, 'minimum', 'maximum');
      case 'boolean': return 'z.boolean()';
      case 'null': return 'z.null()';
      case 'array': return bounded(`z.array(${zodOf(s.items)})`, s, 'minItems', 'maxItems');
      case 'object': {
        if (typeof s.additionalProperties === 'object') return `z.record(z.string(), ${zodOf(s.additionalProperties)})`;
        const required = new Set(s.required ?? []);
        const fields = Object.entries(s.properties).map(([k, v]) => `${/^[A-Za-z_$][\w$]*$/.test(k) ? k : q(k)}: ${zodOf(v)}${required.has(k) ? '' : '.optional()'}`);
        return fields.length ? `z.strictObject({ ${fields.join(', ')} })` : 'z.strictObject({})';
      }
    }
    if (!Object.keys(s).length) return 'z.unknown()';
    throw new Error(`zod inputs: unsupported schema ${JSON.stringify(s)}`);
  }
  const entries = [...inputSchemas].sort(([a], [b]) => a.localeCompare(b)).map(([procedure, s]) => `  ${q(procedure)}: ${zodOf(s)},`);
  const procedures = registry.ingress.filter((g) => g.kind !== 'job').sort((a, b) => a.procedure.localeCompare(b.procedure))
    .map((g) => `  { procedure: ${q(g.procedure)}, kind: ${q(g.kind)}, builder: ${q(g.builder)} },`);
  outputs.set('src/server/trpc/inputs.generated.ts', [
    `// ${GEN}`,
    "import { z } from 'zod';",
    '',
    ...used,
    '',
    '/** The wire input of every ingress procedure that takes one, keyed by procedure path. */',
    'export const INPUTS = {',
    ...entries,
    '};',
    '',
    '/** Every non-job ingress procedure: what router.v2.ts registers, on which builder. */',
    'export const PROCEDURES = [',
    ...procedures,
    '] as const;',
    '',
  ].join('\n'));
}

