for (const file of typeFiles) {
  const src = read(rel(file)).replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
  const re = /export (interface|type) (\w+)(<[^>]*>)?\s*(=)?/g;
  let m;
  while ((m = re.exec(src))) {
    const [, kw, name, generics, eq] = m;
    if (generics) { decls.set(name, { file, kind: 'generic', body: null }); continue; } // located for re-export, never schematized
    let i = re.lastIndex;
    let body;
    if (kw === 'interface') {
      const open = src.indexOf('{', i);
      let depth = 0, j = open;
      for (; j < src.length; j++) { if (src[j] === '{') depth++; else if (src[j] === '}' && --depth === 0) break; }
      body = src.slice(open, j + 1);
    } else {
      if (!eq) continue;
      let depth = 0, j = i;
      for (; j < src.length; j++) {
        const c = src[j];
        if ('{[(<'.includes(c)) depth++; else if ('}])>'.includes(c)) depth--; else if (c === ';' && depth === 0) break;
      }
      body = src.slice(i, j).trim();
    }
    if (decls.has(name) && decls.get(name).file !== file) problems.push(`type ${name} is declared in ${decls.get(name).file} and ${file}`);
    decls.set(name, { file, kind: kw === 'interface' ? 'interface' : 'alias', body });
  }
}

function tokenize(s) {
  const toks = [];
  const re = /\s*(\.\.\.|'(?:[^'\\]|\\.)*'|-?\d+(?:\.\d+)?|[A-Za-z_$][\w$]*|[{}[\]()<>|&:;,?=])/gy;
  let m;
  while ((m = re.exec(s)) && m[0].length) toks.push(m[1]);
  return toks;
}
function parseType(src) {
  const t = tokenize(src);
  let i = 0;
  const peek = () => t[i];
  const eat = (x) => { if (x !== undefined && t[i] !== x) throw new Error(`expected ${x} got ${t[i]} in ${src}`); return t[i++]; };
  function union() {
    if (peek() === '|') eat('|');
    const parts = [inter()];
    while (peek() === '|') { eat('|'); parts.push(inter()); }
    return parts.length === 1 ? parts[0] : { k: 'union', parts };
  }
  function inter() {
    const parts = [postfix()];
    while (peek() === '&') { eat('&'); parts.push(postfix()); }
    return parts.length === 1 ? parts[0] : { k: 'inter', parts };
  }
  function postfix() {
    let base = primary();
    while (peek() === '[' && t[i + 1] === ']') { eat('['); eat(']'); base = { k: 'array', of: base }; }
    return base;
  }
  function primary() {
    const x = peek();
    if (x === '{') return object();
    if (x === '(') { eat('('); const u = union(); eat(')'); return u; }
    if (x === '[') {
      eat('[');
      const first = union();
      let rest = false;
      if (peek() === ',') { eat(','); eat('...'); union(); rest = true; }
      eat(']');
      return { k: 'array', of: first, minItems: rest ? 1 : undefined };
    }
    eat();
    if (x.startsWith("'")) return { k: 'lit', value: x.slice(1, -1) };
    if (/^-?\d/.test(x)) return { k: 'lit', value: Number(x) };
    if (x === 'true' || x === 'false') return { k: 'lit', value: x === 'true' };
    if (peek() === '<') {
      eat('<');
      const args = [union()];
      while (peek() === ',') { eat(','); args.push(union()); }
      eat('>');
      return { k: 'generic', name: x, args };
    }
    return { k: 'ref', name: x };
  }
  function object() {
    eat('{');
    const props = [];
    while (peek() !== '}') {
      if (peek() === 'readonly') eat('readonly');
      const name = eat();
      const optional = peek() === '?' ? (eat('?'), true) : false;
      eat(':');
      props.push({ name, optional, type: union() });
      if (peek() === ';' || peek() === ',') eat();
    }
    eat('}');
    return { k: 'object', props };
  }
  const r = union();
  if (i !== t.length) throw new Error(`trailing tokens in ${src}: ${t.slice(i).join(' ')}`);
  return r;
}
const parsed = new Map();
function typeOf(name) {
  if (!parsed.has(name)) {
    const d = decls.get(name);
    if (!d) throw new Error(`unknown type ${name}`);
    parsed.set(name, parseType(d.body));
  }
  return parsed.get(name);
}

