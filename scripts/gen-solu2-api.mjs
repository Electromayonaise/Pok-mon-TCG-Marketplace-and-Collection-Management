function hostOf(file) { const m = /^src\/modules\/([\w-]+)\//.exec(file); return m ? m[1] : null; }
/** Where `name` should be imported from, seen from `fromFile` (AD-1: other modules via index.ts). */
function importPath(name, fromFile) {
  const d = decls.get(name);
  const fromDir = path.posix.dirname(fromFile);
  const fromHost = hostOf(fromFile);
  const declHost = hostOf(d.file);
  let target;
  if (declHost && declHost !== fromHost) target = `src/modules/${declHost}/index.ts`;
  else target = d.file;
  let r = path.posix.relative(fromDir, target).replace(/\.ts$/, '.js');
  if (!r.startsWith('.')) r = `./${r}`;
  return r;
}
function importBlock(names, fromFile) {
  const byPath = new Map();
  for (const n of [...new Set(names)].filter((n) => n !== 'void' && n !== 'null' && !PRIMS[n])) {
    const p = importPath(n, fromFile);
    byPath.set(p, [...(byPath.get(p) ?? []), n]);
  }
  return [...byPath].sort((a, b) => a[0].localeCompare(b[0])).map(([p, ns]) => `import type { ${ns.sort().join(', ')} } from '${p}';`).join('\n');
}

