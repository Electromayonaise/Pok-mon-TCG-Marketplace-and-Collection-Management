function yaml(v, indent = 0) {
  const pad = ' '.repeat(indent);
  const key = (k) => (/^[A-Za-z_][A-Za-z0-9_.-]*$/.test(k) && !/^(true|false|null|yes|no|on|off)$/i.test(k) ? k : JSON.stringify(k));
  const scalar = (x) => (typeof x === 'string' ? JSON.stringify(x) : String(x));
  if (Array.isArray(v)) {
    if (!v.length) return '[]';
    return v.map((x) => (x !== null && typeof x === 'object' && Object.keys(x).length ? `\n${pad}- ${yaml(x, indent + 2).replace(/^\n\s*/, '')}` : `\n${pad}- ${x !== null && typeof x === 'object' ? (Array.isArray(x) ? '[]' : '{}') : scalar(x)}`)).join('');
  }
  if (v !== null && typeof v === 'object') {
    const entries = Object.entries(v);
    if (!entries.length) return '{}';
    return entries.map(([k, x]) => {
      if (x !== null && typeof x === 'object' && (Array.isArray(x) ? x.length : Object.keys(x).length)) return `\n${pad}${key(k)}:${yaml(x, indent + 2)}`;
      return `\n${pad}${key(k)}: ${x !== null && typeof x === 'object' ? (Array.isArray(x) ? '[]' : '{}') : scalar(x)}`;
    }).join('');
  }
  return scalar(v);
}
