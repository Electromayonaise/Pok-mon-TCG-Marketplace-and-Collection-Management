function schemaOf(node) {
  switch (node.k) {
    case 'lit': return typeof node.value === 'string' ? { type: 'string', const: node.value } : { const: node.value };
    case 'array': return { type: 'array', items: schemaOf(node.of), ...(node.minItems ? { minItems: node.minItems } : {}) };
    case 'object': {
      const properties = {};
      const required = [];
      for (const p of node.props) { properties[p.name] = withConstraints(schemaOf(p.type), p.constraints, p.name); if (!p.optional) required.push(p.name); }
      return { type: 'object', additionalProperties: false, properties, ...(required.length ? { required } : {}) };
    }
    case 'inter': return { allOf: node.parts.map(schemaOf) };
    case 'union': {
      const lits = node.parts.filter((p) => p.k === 'lit' && typeof p.value === 'string');
      const nulls = node.parts.filter((p) => p.k === 'ref' && p.name === 'null');
      if (lits.length + nulls.length === node.parts.length) {
        return { type: nulls.length ? ['string', 'null'] : 'string', enum: [...lits.map((l) => l.value), ...(nulls.length ? [null] : [])] };
      }
      return { anyOf: node.parts.map(schemaOf) };
    }
    case 'generic':
      if (node.name === 'Record') return { type: 'object', additionalProperties: schemaOf(node.args[1]) };
      throw new Error(`unsupported generic ${node.name}`);
    case 'ref': {
      if (PRIMS[node.name]) return PRIMS[node.name];
      if (!components.has(node.name)) { components.set(node.name, null); components.set(node.name, schemaOf(typeOf(node.name))); }
      return { $ref: `#/components/schemas/${node.name}` };
    }
  }
  throw new Error(`unknown node ${node.k}`);
}
