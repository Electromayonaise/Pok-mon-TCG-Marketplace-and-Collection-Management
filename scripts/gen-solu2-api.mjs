// A small parser for the subset the DTO files use: interfaces, aliases, unions, intersections,
// arrays, tuples, inline objects, literals, Record<K, V> and references.
function listTs(dir) {
  const out = [];
  for (const e of fs.readdirSync(rel(dir), { withFileTypes: true })) {
    const p = path.posix.join(dir, e.name);
    if (e.isDirectory()) out.push(...listTs(p));
    else if (e.name.endsWith('.ts')) out.push(p);
  }
  return out;
}
