// Readiness check 2 (task statement §7) / review G-17: every UI state of every UX page spec is
// backed by a contract and a DTO. Reads the "Page States" table of each page spec, maps the page
// to registry operations through schemas/ui-states.json, classifies each state and writes
// docs/solu-2/planning/detailed-design/ui-states.md.
//   client  — a transport or interaction state with no server data (loading, network error)
//   data    — rendered from the response DTOs of the page's operations
//   refusal — rendered from ErrorBody; the page's operations must declare at least one code
// Usage: node scripts/check-ui-states.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8').replace(/\r\n/g, '\n');
const DD = 'docs/solu-2/planning/detailed-design';
const map = JSON.parse(read(`${DD}/schemas/ui-states.json`));
const reg = JSON.parse(read(`${DD}/schemas/operations.json`));
const ops = new Map(reg.operations.map((o) => [o.id, o]));
const errorsByOp = new Map();
// Codes every procedure builder adds (the same table as gen-solu2-api.mjs; AD-SYS-8 rule 2).
const BUILDER = { public: [], authed: ['NotAuthenticated'], canBuy: ['NotAuthenticated', 'EmailNotVerified'], admin: ['NotAuthenticated', 'AdminOnly'], job: [] };
for (const g of reg.ingress) errorsByOp.set(g.op, [...new Set([...(errorsByOp.get(g.op) ?? []), ...BUILDER[g.builder], ...(g.kind === 'job' ? [] : ['RequestValidationFailed']), ...g.errors])]);
const CLIENT = new RegExp(map.classes.client, 'i');
const REFUSAL = new RegExp(map.classes.refusal, 'i');
const DATA = new RegExp(map.classes.data, 'i');

const scenarioRoot = 'docs/plan-2/ux/C-UX-Scenarios';
const pages = [];
for (const dir of fs.readdirSync(path.join(ROOT, scenarioRoot)).sort()) {
  const full = path.join(ROOT, scenarioRoot, dir);
  if (!fs.statSync(full).isDirectory()) continue;
  for (const sub of fs.readdirSync(full).sort()) {
    const subFull = path.join(full, sub);
    if (!fs.statSync(subFull).isDirectory()) continue;
    for (const f of fs.readdirSync(subFull).filter((x) => x.endsWith('.md'))) {
      const rel = `${scenarioRoot}/${dir}/${sub}/${f}`;
      const text = read(rel);
      const title = /^# (.+)$/m.exec(text)?.[1] ?? f;
      const id = /^(\d+\.\d+)\b/.exec(title)?.[1];
      const block = /## Page States\n([\s\S]*?)(?:\n## |$)/.exec(text)?.[1] ?? '';
      const states = block.split('\n')
        .filter((l) => l.startsWith('|') && !/^\|\s*(State|-{3,})/.test(l))
        .map((l) => l.replace(/^\|/, '').split('|')[0].trim())
        .filter(Boolean);
      pages.push({ id, title, rel, states });
    }
  }
}

const problems = [];
const out = ['# UI states → contracts and DTOs', '', `GENERATED by scripts/check-ui-states.mjs from \`schemas/ui-states.json\`, \`schemas/operations.json\` and the "Page States" tables of the UX page specs. Do not edit by hand.`, ''];
const counts = { client: 0, data: 0, refusal: 0 };
const body = [];
pages.sort((a, b) => a.id.localeCompare(b.id, undefined, { numeric: true }));
for (const p of pages) {
  if (!p.id) { problems.push(`${p.rel}: no page id in the title`); continue; }
  const entry = map.pages[p.id];
  if (!entry) { problems.push(`page ${p.id} (${p.title}) has no entry in ui-states.json`); continue; }
  if (!p.states.length) problems.push(`page ${p.id}: no Page States table`);
  const pageOps = entry.ops.map((id) => { const o = ops.get(id); if (!o) problems.push(`page ${p.id}: unknown operation ${id}`); return o; }).filter(Boolean);
  const dtos = [...new Set(pageOps.map((o) => o.response).filter((t) => t !== 'void'))];
  const codes = [...new Set(entry.ops.flatMap((id) => errorsByOp.get(id) ?? []))];
  body.push(`## ${p.title}${entry.dev ? ' *(H console, §9.2)*' : ''}`, '', `Operations: ${entry.ops.map((id) => `\`${id}\``).join(', ')}`, '', '| State | Class | Backed by |', '|---|---|---|');
  for (const s of p.states) {
    const name = s.replace(/`/g, '');
    // Review E-2: a state must match a class explicitly; nothing defaults to `data`.
    let cls;
    if (CLIENT.test(name)) cls = 'client';
    else if (REFUSAL.test(s)) cls = 'refusal';
    else if (DATA.test(name)) cls = 'data';
    else { problems.push(`page ${p.id} state "${s}" matches no class in ui-states.json`); continue; }
    counts[cls]++;
    let backing;
    if (cls === 'client') backing = 'transport or interaction; no server DTO';
    else if (cls === 'data') backing = dtos.length ? dtos.map((d) => `\`${d}\``).join(', ') : '—';
    else backing = codes.length ? `\`ErrorBody\` (${codes.map((c) => `\`${c}\``).join(', ')})` : '—';
    if (backing === '—') problems.push(`page ${p.id} state "${s}" (${cls}) has no backing ${cls === 'data' ? 'DTO' : 'error code'}`);
    body.push(`| ${s.replace(/\|/g, '\\|')} | ${cls} | ${backing} |`);
  }
  body.push('');
}
for (const id of Object.keys(map.pages)) if (!pages.some((p) => p.id === id)) problems.push(`ui-states.json names page ${id}, which has no page spec`);
const total = counts.client + counts.data + counts.refusal;
out.push(`**${pages.length} pages, ${total} states:** ${counts.data} data, ${counts.refusal} refusal, ${counts.client} client-only. Every data state names the response DTOs of its page's operations, and every refusal names the \`ErrorBody\` codes those operations declare in \`operations.json\`.`, '', ...body);
const text = `${out.join('\n')}\n`;
const target = path.join(ROOT, DD, 'ui-states.md');
if (problems.length) { console.log(problems.join('\n')); }
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : null;
  if (cur !== text) problems.push('ui-states.md is stale (run node scripts/check-ui-states.mjs)');
} else fs.writeFileSync(target, text);
console.log(`${pages.length} pages, ${total} states (${counts.data} data, ${counts.refusal} refusal, ${counts.client} client), ${problems.length} problems`);
process.exit(problems.length ? 1 : 0);
