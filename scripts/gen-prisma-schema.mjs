// Generates prisma/schema.prisma from the migrations (R-8, G-13): it migrates a scratch
// database, introspects it with `prisma db pull --print`, and tags every model with the module
// that owns its table (the DDL's section headers, AD-8), so the model can never drift from the
// SQL that is the schema source of truth.
//
// Usage: node scripts/gen-prisma-schema.mjs          write prisma/schema.prisma
//        node scripts/gen-prisma-schema.mjs --check  exit 1 if prisma/schema.prisma differs
// Connects like the test harness (TEZG_PG_* variables, default: the Compose Postgres).
import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import pg from 'pg';
import { MIGRATIONS_DIR, migrationFiles } from './lib/migrations.mjs';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const OUT = path.join(ROOT, 'prisma/schema.prisma');
const check = process.argv.includes('--check');

// The generator and datasource blocks are this script's; introspection supplies only the models.
const HEADER = `// GENERATED by scripts/gen-prisma-schema.mjs from the migrations in _bmad-output/planning-artifacts/detailed-design/schemas. Do not edit by hand.

generator client {
  provider        = "prisma-client"
  output          = "../generated/prisma"
  previewFeatures = ["partialIndexes"]
}

datasource db {
  provider = "postgresql"
}
`;

const PG = {
  host: process.env.TEZG_PG_HOST ?? '127.0.0.1',
  port: Number(process.env.TEZG_PG_PORT ?? 55432),
  user: process.env.TEZG_PG_USER ?? 'tezg',
  password: process.env.TEZG_PG_PASSWORD ?? 'tezg',
};
const SCRATCH = `tezg_prisma_pull_${process.pid}`;
const files = migrationFiles(path.join(ROOT, MIGRATIONS_DIR));

// Table -> owning module, from the section headers (the same rule as the AD-8 fitness scan).
const owners = new Map();
for (const { sql } of files) {
  let owner = '';
  for (const line of sql.split('\n')) {
    const h = /^-- (shared-kernel|identity|catalog|listings|orders|commission|trading|messaging|collections|reviews)\b/.exec(line);
    if (h) owner = h[1];
    const t = /^CREATE TABLE IF NOT EXISTS "?(\w+)"?/.exec(line);
    if (t && owner) owners.set(t[1], owner);
  }
}

// Introspects the scratch database. `--force` ignores the committed model, and the base schema is
// a temporary header-only file, so a stale or hand-edited prisma/schema.prisma cannot leak in.
function introspect(url) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'tezg-prisma-'));
  try {
    const base = path.join(dir, 'schema.prisma');
    fs.writeFileSync(base, HEADER);
    const run = spawnSync(process.execPath, [path.join(ROOT, 'node_modules/prisma/build/index.js'), 'db', 'pull', '--print', '--force', '--schema', base], {
      cwd: ROOT,
      env: { ...process.env, DATABASE_URL: url },
      encoding: 'utf8',
    });
    if (run.status !== 0) throw new Error(run.stderr || run.stdout);
    return run.stdout.replace(/\r\n/g, '\n');
  } finally {
    fs.rmSync(dir, { recursive: true, force: true });
  }
}

const admin = new pg.Client({ ...PG, database: 'postgres' });
await admin.connect();
let printed;
try {
  await admin.query(`DROP DATABASE IF EXISTS ${pg.escapeIdentifier(SCRATCH)} WITH (FORCE)`);
  await admin.query(`CREATE DATABASE ${pg.escapeIdentifier(SCRATCH)}`);
  const scratch = new pg.Client({ ...PG, database: SCRATCH });
  await scratch.connect();
  try {
    for (const f of files) await scratch.query(f.sql);
  } finally {
    await scratch.end();
  }
  printed = introspect(`postgresql://${encodeURIComponent(PG.user)}:${encodeURIComponent(PG.password)}@${PG.host}:${PG.port}/${SCRATCH}`);
} finally {
  await admin.query(`DROP DATABASE IF EXISTS ${pg.escapeIdentifier(SCRATCH)} WITH (FORCE)`);
  await admin.end();
}

// The model blocks, in introspection order: name -> body lines (without the braces).
const blocks = new Map();
for (const m of printed.matchAll(/^((?:\/\/\/[^\n]*\n)*)model (\w+) \{\n([\s\S]*?)^\}/gm)) {
  blocks.set(m[2], { docs: m[1].split('\n').filter(Boolean), body: m[3].split('\n').filter((l) => l.length) });
}
const fieldAttrs = (body, name) => body.map((l) => new RegExp(`^\\s+${name}\\s+\\S+\\s*(.*)$`).exec(l)).find(Boolean)?.[1] ?? '';

// Introspection reads a composite foreign key whose columns are unique as a one-to-one relation,
// and Prisma then rejects the model unless the defining side declares the column pair unique.
// Two cases occur in the DDL; neither changes it:
//   - a column of the pair is unique on its own (`@id`, or `@unique` without `where`): the pair
//     is unique too, so the implied `@@unique` is declared (IndividualSellerProfile, BusinessProfile);
//   - the column is unique only under a partial index (`@unique(where: ...)`): the relation is
//     one-to-many, so the back-relation becomes a list (User.BusinessApplication: one pending
//     application per business, any number of decided ones).
const problems = [];
for (const [model, block] of blocks) {
  for (const line of [...block.body]) {
    const r = /^\s+\w+\s+(\w+)\??\s+@relation\((?:"[^"]*", )?fields: \[([\w, ]+)\]/.exec(line);
    if (!r) continue;
    const [, target, list] = r;
    const fields = list.split(', ');
    if (fields.length < 2) continue;
    const attrs = fields.map((f) => fieldAttrs(block.body, f));
    if (attrs.some((a) => /@id\b|@unique(?!\([^)]*where:)/.test(a))) {
      const unique = `  @@unique([${fields.join(', ')}])`;
      if (!block.body.includes(unique)) block.body.push(...(block.body.some((l) => /^\s+@@/.test(l)) ? [] : ['']), unique);
    } else if (attrs.some((a) => /@unique\([^)]*where:/.test(a))) {
      const back = blocks.get(target)?.body;
      const i = back?.findIndex((l) => new RegExp(`^\\s+\\w+\\s+${model}\\?(\\s|$)`).test(l)) ?? -1;
      if (i < 0) problems.push(`${model} -> ${target}: no optional back-relation to make a list`);
      else back[i] = back[i].replace(`${model}?`, `${model}[]`);
    }
  }
}

const out = [HEADER];
for (const [model, block] of blocks) {
  const owner = owners.get(model);
  if (!owner) problems.push(`model ${model}: no owning module in the DDL section headers`);
  out.push(`/// @owner ${owner ?? 'unknown'}`, ...block.docs, `model ${model} {`, ...block.body, '}', '');
}
for (const t of owners.keys()) if (!blocks.has(t)) problems.push(`table ${t}: no model in the introspected schema`);
if (/^(enum|view|type) /m.test(printed)) problems.push('introspection produced an enum, view or type block, which this generator does not carry over');
if (problems.length) {
  console.error(problems.join('\n'));
  process.exit(1);
}
const text = `${out.join('\n').trimEnd()}\n`;

if (check) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== text) {
    console.error('prisma/schema.prisma is stale: run `npm run db:pull`');
    process.exit(1);
  }
  console.log(`${blocks.size} models, each tagged with its owning module; prisma/schema.prisma is current`);
} else {
  fs.writeFileSync(OUT, text);
  console.log(`${blocks.size} models written to prisma/schema.prisma`);
}
